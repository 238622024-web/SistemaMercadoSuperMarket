create table if not exists public.stock_movements (
    id bigint generated by default as identity primary key,
    product_id bigint not null references public.produtos(id) on delete restrict,
    tipo text not null check (tipo in ('entrada', 'saida', 'ajuste')),
    quantidade numeric(14, 3) not null check (quantidade > 0),
    estoque_anterior numeric(14, 3) not null check (estoque_anterior >= 0),
    estoque_posterior numeric(14, 3) not null check (estoque_posterior >= 0),
    motivo text not null check (motivo in ('compra', 'devolucao', 'perda', 'vencimento', 'inventario', 'outro')),
    observacoes text,
    referencia text,
    performed_by uuid references auth.users(id) on delete set null,
    created_at timestamptz not null default now()
);

create index if not exists stock_movements_product_created_idx
    on public.stock_movements (product_id, created_at desc);

alter table public.stock_movements enable row level security;
grant all on table public.stock_movements to service_role;
grant usage, select on sequence public.stock_movements_id_seq to service_role;

create or replace function public.adjust_product_stock(
    p_product_id bigint,
    p_type text,
    p_quantity numeric,
    p_reason text,
    p_notes text,
    p_performed_by uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_before numeric(14, 3);
    v_after numeric(14, 3);
    v_delta numeric(14, 3);
    v_movement_id bigint;
    v_tipo text;
begin
    if p_type not in ('in', 'out', 'set')
       or p_reason not in ('compra', 'devolucao', 'perda', 'vencimento', 'inventario', 'outro')
       or p_quantity is null
       or p_quantity < 0
       or p_quantity > 1000000
       or (p_type <> 'set' and p_quantity = 0)
       or length(coalesce(p_notes, '')) > 500 then
        raise exception 'Informe uma quantidade, tipo e motivo válidos.';
    end if;

    select coalesce(estoque_atual, 0)::numeric(14, 3)
      into v_before
      from public.produtos
     where id = p_product_id
     for update;

    if not found then
        raise exception 'Produto não encontrado.';
    end if;

    if p_type = 'in' then
        v_after := v_before + p_quantity;
        v_tipo := 'entrada';
    elsif p_type = 'out' then
        if p_quantity > v_before then
            raise exception 'Estoque insuficiente. Saldo atual: %.', v_before;
        end if;
        v_after := v_before - p_quantity;
        v_tipo := 'saida';
    else
        v_after := p_quantity;
        v_tipo := 'ajuste';
    end if;

    v_delta := abs(v_after - v_before);
    if v_delta = 0 then
        raise exception 'O saldo informado é igual ao estoque atual.';
    end if;

    update public.produtos
       set estoque_atual = v_after
     where id = p_product_id;

    insert into public.stock_movements (
        product_id, tipo, quantidade, estoque_anterior, estoque_posterior,
        motivo, observacoes, performed_by
    ) values (
        p_product_id, v_tipo, v_delta, v_before, v_after,
        p_reason, nullif(trim(p_notes), ''), p_performed_by
    )
    returning id into v_movement_id;

    return jsonb_build_object(
        'id', v_movement_id,
        'product_id', p_product_id,
        'tipo', v_tipo,
        'quantidade', v_delta,
        'estoque_anterior', v_before,
        'estoque_posterior', v_after
    );
end;
$$;

create or replace function public.receive_purchase_order(
    p_order_id bigint,
    p_performed_by uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_order public.purchase_orders%rowtype;
    v_item jsonb;
    v_product_id bigint;
    v_before numeric(14, 3);
    v_quantity numeric(14, 3);
    v_received integer := 0;
begin
    select * into v_order
      from public.purchase_orders
     where id = p_order_id
     for update;

    if not found then
        raise exception 'Pedido de compra não encontrado.';
    end if;
    if v_order.status <> 'ordered' then
        raise exception 'Somente pedidos em aberto podem ser recebidos.';
    end if;
    if jsonb_typeof(v_order.itens) <> 'array' or jsonb_array_length(v_order.itens) = 0 then
        raise exception 'O pedido não possui itens para receber.';
    end if;

    for v_item in select value from jsonb_array_elements(v_order.itens)
    loop
        v_product_id := null;
        if coalesce(v_item->>'produto_id', '') ~ '^[0-9]+$' then
            v_product_id := (v_item->>'produto_id')::bigint;
        elsif coalesce(v_item->>'codigo', '') <> '' then
            select id into v_product_id
              from public.produtos
             where codigo = v_item->>'codigo'
                or codigo_barras = v_item->>'codigo'
             order by id
             limit 1;
        end if;

        if v_product_id is null then
            raise exception 'O item "%" não está vinculado a um produto. Crie um novo pedido selecionando um produto cadastrado.', coalesce(v_item->>'nome', 'sem nome');
        end if;

        v_quantity := (v_item->>'quantidade')::numeric;
        if v_quantity is null or v_quantity <= 0 then
            raise exception 'Quantidade inválida no item "%".', coalesce(v_item->>'nome', 'sem nome');
        end if;

        select coalesce(estoque_atual, 0)::numeric(14, 3)
          into v_before
          from public.produtos
         where id = v_product_id
         for update;

        if not found then
            raise exception 'O produto vinculado ao item "%" não existe mais.', coalesce(v_item->>'nome', 'sem nome');
        end if;

        update public.produtos
           set estoque_atual = v_before + v_quantity
         where id = v_product_id;

        insert into public.stock_movements (
            product_id, tipo, quantidade, estoque_anterior, estoque_posterior,
            motivo, observacoes, referencia, performed_by
        ) values (
            v_product_id, 'entrada', v_quantity, v_before, v_before + v_quantity,
            'compra', 'Recebimento do pedido de compra ' || v_order.numero,
            v_order.numero, p_performed_by
        );
        v_received := v_received + 1;
    end loop;

    update public.purchase_orders
       set status = 'received', updated_at = now()
     where id = v_order.id;

    return jsonb_build_object(
        'id', v_order.id,
        'numero', v_order.numero,
        'status', 'received',
        'itens_recebidos', v_received
    );
end;
$$;

revoke all on function public.adjust_product_stock(bigint, text, numeric, text, text, uuid) from public;
revoke all on function public.receive_purchase_order(bigint, uuid) from public;
grant execute on function public.adjust_product_stock(bigint, text, numeric, text, text, uuid) to service_role;
grant execute on function public.receive_purchase_order(bigint, uuid) to service_role;
