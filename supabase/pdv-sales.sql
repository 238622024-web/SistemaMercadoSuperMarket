create table if not exists public.pdv_sales (
    id bigint generated by default as identity primary key,
    sale_number text unique,
    shift_id uuid not null references public.pdv_shifts(id) on delete restrict,
    operator_id uuid not null references auth.users(id) on delete restrict,
    operator_name text not null,
    register_number smallint not null check (register_number in (1, 2)),
    payment_method text not null check (payment_method in ('money', 'debit', 'credit', 'pix', 'elo_meal', 'elo_food')),
    total numeric(14, 2) not null check (total >= 0),
    status text not null default 'completed' check (status = 'completed'),
    created_at timestamptz not null default now()
);

create index if not exists pdv_sales_created_at_idx
    on public.pdv_sales (created_at desc);

create index if not exists pdv_sales_operator_created_at_idx
    on public.pdv_sales (operator_id, created_at desc);

create table if not exists public.pdv_sale_items (
    id bigint generated by default as identity primary key,
    sale_id bigint not null references public.pdv_sales(id) on delete restrict,
    product_id bigint not null references public.produtos(id) on delete restrict,
    product_name text not null,
    quantity numeric(14, 3) not null check (quantity > 0),
    unit_price numeric(12, 2) not null check (unit_price >= 0),
    line_total numeric(14, 2) not null check (line_total >= 0)
);

create index if not exists pdv_sale_items_sale_id_idx
    on public.pdv_sale_items (sale_id);

alter table public.pdv_sales enable row level security;
alter table public.pdv_sale_items enable row level security;
grant all on table public.pdv_sales, public.pdv_sale_items to service_role;
grant usage, select on sequence public.pdv_sales_id_seq, public.pdv_sale_items_id_seq to service_role;

create or replace function public.complete_pdv_sale(
    p_shift_id uuid,
    p_operator_id uuid,
    p_payment_method text,
    p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_shift public.pdv_shifts%rowtype;
    v_item record;
    v_product public.produtos%rowtype;
    v_sale_id bigint;
    v_sale_number text;
    v_total numeric(14, 2) := 0;
    v_line_total numeric(14, 2);
    v_lines jsonb := '[]'::jsonb;
begin
    if p_payment_method is null
       or p_payment_method not in ('money', 'debit', 'credit', 'pix', 'elo_meal', 'elo_food') then
        raise exception 'Selecione uma forma de pagamento válida.';
    end if;
    if p_items is null or jsonb_typeof(p_items) <> 'array' then
        raise exception 'Adicione de 1 a 100 produtos para concluir a venda.';
    end if;
    if jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 100 then
        raise exception 'Adicione de 1 a 100 produtos para concluir a venda.';
    end if;

    select * into v_shift
      from public.pdv_shifts
     where id = p_shift_id
       and operator_id = p_operator_id
       and closed_at is null
     for update;
    if not found then
        raise exception 'O caixa não está aberto ou não pertence a este operador.';
    end if;

    for v_item in
        select (entry->>'product_id')::bigint as product_id,
               sum((entry->>'quantity')::numeric) as quantity
          from jsonb_array_elements(p_items) as items(entry)
         group by (entry->>'product_id')::bigint
         order by (entry->>'product_id')::bigint
    loop
        if v_item.product_id is null
           or v_item.quantity is null
           or v_item.product_id <= 0
           or v_item.quantity <= 0
           or v_item.quantity > 1000000
           or v_item.quantity * 1000 <> trunc(v_item.quantity * 1000) then
            raise exception 'Um dos produtos tem uma quantidade inválida.';
        end if;

        select * into v_product
          from public.produtos
         where id = v_item.product_id
         for update;
        if not found or v_product.ativo is not true then
            raise exception 'Um produto da venda não existe mais ou está inativo.';
        end if;
        if coalesce(v_product.estoque_atual, 0) < v_item.quantity then
            raise exception 'Estoque insuficiente para "%". Disponível: %.',
                v_product.nome, coalesce(v_product.estoque_atual, 0);
        end if;
        if v_product.preco_venda is null or v_product.preco_venda < 0 then
            raise exception 'O preço do produto "%" é inválido.', v_product.nome;
        end if;

        v_line_total := round(v_product.preco_venda::numeric * v_item.quantity, 2);
        v_total := v_total + v_line_total;
        v_lines := v_lines || jsonb_build_array(jsonb_build_object(
            'product_id', v_product.id,
            'product_name', v_product.nome,
            'quantity', v_item.quantity,
            'unit_price', v_product.preco_venda,
            'line_total', v_line_total
        ));
    end loop;

    insert into public.pdv_sales (
        shift_id, operator_id, operator_name, register_number, payment_method, total
    ) values (
        v_shift.id, v_shift.operator_id, v_shift.operator_name,
        v_shift.register_number, p_payment_method, v_total
    )
    returning id into v_sale_id;

    v_sale_number := 'VD-' || lpad(v_sale_id::text, 8, '0');
    update public.pdv_sales
       set sale_number = v_sale_number
     where id = v_sale_id;

    for v_item in
        select line.product_id, line.product_name, line.quantity,
               line.unit_price, line.line_total
          from jsonb_to_recordset(v_lines) as line(
              product_id bigint,
              product_name text,
              quantity numeric,
              unit_price numeric,
              line_total numeric
          )
         order by line.product_id
    loop
        select * into v_product
          from public.produtos
         where id = v_item.product_id
         for update;

        update public.produtos
           set estoque_atual = coalesce(estoque_atual, 0) - v_item.quantity
         where id = v_item.product_id;

        insert into public.pdv_sale_items (
            sale_id, product_id, product_name, quantity, unit_price, line_total
        ) values (
            v_sale_id, v_item.product_id, v_item.product_name,
            v_item.quantity, v_item.unit_price, v_item.line_total
        );

        insert into public.stock_movements (
            product_id, tipo, quantidade, estoque_anterior, estoque_posterior,
            motivo, observacoes, referencia, performed_by
        ) values (
            v_item.product_id, 'saida', v_item.quantity,
            coalesce(v_product.estoque_atual, 0),
            coalesce(v_product.estoque_atual, 0) - v_item.quantity,
            'outro', 'Venda ' || v_sale_number, v_sale_number, p_operator_id
        );
    end loop;

    return jsonb_build_object(
        'id', v_sale_id,
        'sale_number', v_sale_number,
        'shift_id', v_shift.id,
        'operator_id', v_shift.operator_id,
        'operator_name', v_shift.operator_name,
        'register_number', v_shift.register_number,
        'payment_method', p_payment_method,
        'total', v_total,
        'status', 'completed',
        'created_at', now()
    );
end;
$$;

revoke all on function public.complete_pdv_sale(uuid, uuid, text, jsonb) from public;
revoke all on function public.complete_pdv_sale(uuid, uuid, text, jsonb) from anon, authenticated;
grant execute on function public.complete_pdv_sale(uuid, uuid, text, jsonb) to service_role;
