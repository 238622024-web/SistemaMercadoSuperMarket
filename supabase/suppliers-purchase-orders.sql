create table if not exists public.suppliers (
    id bigint generated by default as identity primary key,
    nome text not null check (char_length(nome) between 2 and 160),
    razao_social text,
    cnpj text,
    categoria text,
    contato text,
    telefone text,
    email text,
    endereco text,
    cidade text,
    estado text check (estado is null or char_length(estado) = 2),
    cep text,
    prazo_pagamento integer not null default 0 check (prazo_pagamento between 0 and 365),
    observacoes text,
    ativo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index if not exists suppliers_cnpj_unique
    on public.suppliers (cnpj)
    where cnpj is not null;

create index if not exists suppliers_nome_idx
    on public.suppliers (nome);

create table if not exists public.purchase_orders (
    id bigint generated by default as identity primary key,
    numero text not null unique,
    supplier_id bigint not null references public.suppliers(id) on delete restrict,
    created_by uuid references auth.users(id) on delete set null,
    data_entrega date,
    observacoes text,
    itens jsonb not null check (jsonb_typeof(itens) = 'array'),
    total numeric(12, 2) not null check (total >= 0),
    status text not null default 'ordered'
        check (status in ('ordered', 'received', 'cancelled')),
    email_status text not null default 'pending'
        check (email_status in ('pending', 'sent', 'failed')),
    email_sent_at timestamptz,
    email_error text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists purchase_orders_supplier_created_idx
    on public.purchase_orders (supplier_id, created_at desc);

create index if not exists purchase_orders_status_created_idx
    on public.purchase_orders (status, created_at desc);

create table if not exists public.financial_expenses (
    id bigint generated by default as identity primary key,
    descricao text not null check (char_length(descricao) between 2 and 160),
    fornecedor text check (fornecedor is null or char_length(fornecedor) <= 160),
    categoria text not null check (char_length(categoria) between 2 and 80),
    valor numeric(12, 2) not null check (valor >= 0),
    data_vencimento date not null,
    status text not null default 'pending' check (status in ('pending', 'paid')),
    paid_at timestamptz,
    purchase_order_id bigint unique references public.purchase_orders(id) on delete cascade,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint financial_expenses_paid_at_status_check
        check ((status = 'paid' and paid_at is not null) or (status = 'pending' and paid_at is null))
);

create index if not exists financial_expenses_due_status_idx
    on public.financial_expenses (status, data_vencimento);

create or replace function public.create_purchase_order_expense()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    supplier_name text;
    payment_term integer;
begin
    select nome, prazo_pagamento
      into supplier_name, payment_term
      from public.suppliers
     where id = new.supplier_id;

    insert into public.financial_expenses (
        descricao,
        fornecedor,
        categoria,
        valor,
        data_vencimento,
        purchase_order_id
    ) values (
        new.numero,
        supplier_name,
        'Estoque',
        new.total,
        new.created_at::date + coalesce(payment_term, 0),
        new.id
    )
    on conflict (purchase_order_id) do nothing;

    return new;
end;
$$;

drop trigger if exists purchase_orders_create_expense on public.purchase_orders;
create trigger purchase_orders_create_expense
    after insert on public.purchase_orders
    for each row execute function public.create_purchase_order_expense();

insert into public.financial_expenses (
    descricao,
    fornecedor,
    categoria,
    valor,
    data_vencimento,
    purchase_order_id
)
select
    orders.numero,
    suppliers.nome,
    'Estoque',
    orders.total,
    orders.created_at::date + coalesce(suppliers.prazo_pagamento, 0),
    orders.id
from public.purchase_orders as orders
join public.suppliers as suppliers on suppliers.id = orders.supplier_id
on conflict (purchase_order_id) do nothing;

alter table public.suppliers enable row level security;
alter table public.purchase_orders enable row level security;
alter table public.financial_expenses enable row level security;

grant all on table public.suppliers to service_role;
grant all on table public.purchase_orders to service_role;
grant all on table public.financial_expenses to service_role;
grant usage, select on sequence public.suppliers_id_seq to service_role;
grant usage, select on sequence public.purchase_orders_id_seq to service_role;
grant usage, select on sequence public.financial_expenses_id_seq to service_role;
